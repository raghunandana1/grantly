import React, { useRef, useEffect } from 'react';

/**
 * 2D Perlin Noise Implementation for Interactive Waves
 */
class Grad {
  constructor(x, y, z) {
    this.x = x;
    this.y = y;
    this.z = z;
  }
  dot2(x, y) {
    return this.x * x + this.y * y;
  }
}

